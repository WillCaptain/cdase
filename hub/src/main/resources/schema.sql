CREATE TABLE IF NOT EXISTS api_parameters (
    api_id       VARCHAR(512) NOT NULL,
    version      VARCHAR(128) NOT NULL,
    direction    VARCHAR(16) NOT NULL,
    ordinal      INTEGER NOT NULL,
    param_name   VARCHAR(255) NOT NULL,
    param_type   VARCHAR(512),
    description  CLOB,
    is_required  BOOLEAN NOT NULL,
    CONSTRAINT pk_api_parameters PRIMARY KEY (api_id, version, direction, ordinal),
    CONSTRAINT fk_api_parameters_version FOREIGN KEY (api_id, version)
        REFERENCES api_versions(api_id, version) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS api_usage_guidance (
    api_id       VARCHAR(512) NOT NULL,
    version      VARCHAR(128) NOT NULL,
    guidance_type VARCHAR(32) NOT NULL,
    ordinal      INTEGER NOT NULL,
    guidance_text CLOB NOT NULL,
    CONSTRAINT pk_api_usage PRIMARY KEY (api_id, version, guidance_type, ordinal),
    CONSTRAINT fk_api_usage_version FOREIGN KEY (api_id, version)
        REFERENCES api_versions(api_id, version) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS api_errors (
    api_id      VARCHAR(512) NOT NULL,
    version     VARCHAR(128) NOT NULL,
    error_code  VARCHAR(255) NOT NULL,
    description CLOB,
    CONSTRAINT pk_api_errors PRIMARY KEY (api_id, version, error_code),
    CONSTRAINT fk_api_errors_version FOREIGN KEY (api_id, version)
        REFERENCES api_versions(api_id, version) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS api_side_effects (
    api_id      VARCHAR(512) NOT NULL,
    version     VARCHAR(128) NOT NULL,
    ordinal     INTEGER NOT NULL,
    effect_text CLOB NOT NULL,
    CONSTRAINT pk_api_side_effects PRIMARY KEY (api_id, version, ordinal),
    CONSTRAINT fk_api_side_effects_version FOREIGN KEY (api_id, version)
        REFERENCES api_versions(api_id, version) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS api_discovery_evidence (
    api_id       VARCHAR(512) NOT NULL,
    version      VARCHAR(128) NOT NULL,
    ordinal      INTEGER NOT NULL,
    evidence_kind VARCHAR(64) NOT NULL,
    source_path  VARCHAR(1024) NOT NULL,
    source_line  INTEGER,
    source_symbol VARCHAR(512),
    detail       CLOB,
    CONSTRAINT pk_api_discovery_evidence PRIMARY KEY (api_id, version, ordinal),
    CONSTRAINT fk_api_discovery_evidence_version FOREIGN KEY (api_id, version)
        REFERENCES api_versions(api_id, version) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS api_relations (
    api_id             VARCHAR(512) NOT NULL,
    version            VARCHAR(128) NOT NULL,
    relation_type      VARCHAR(64) NOT NULL,
    target_api_id      VARCHAR(512) NOT NULL,
    target_version     VARCHAR(128),
    CONSTRAINT pk_api_relations PRIMARY KEY
        (api_id, version, relation_type, target_api_id),
    CONSTRAINT fk_api_relations_version FOREIGN KEY (api_id, version)
        REFERENCES api_versions(api_id, version) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS api_lifecycle_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_id         VARCHAR(512) NOT NULL,
    version        VARCHAR(128) NOT NULL,
    from_status    VARCHAR(32),
    to_status      VARCHAR(32) NOT NULL,
    actor          VARCHAR(255),
    note           CLOB,
    related_version VARCHAR(128),
    occurred_at    TIMESTAMP NOT NULL,
    CONSTRAINT fk_api_events_version FOREIGN KEY (api_id, version)
        REFERENCES api_versions(api_id, version) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_api_operations_scope
    ON api_operations(system_key, module_key, operation_name);
CREATE INDEX IF NOT EXISTS idx_api_versions_status
    ON api_versions(lifecycle_status, updated_at);
CREATE INDEX IF NOT EXISTS idx_api_relations_target
    ON api_relations(target_api_id);
